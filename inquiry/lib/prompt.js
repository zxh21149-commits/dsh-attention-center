import { totalQuestions } from './config.js'

function renderQuestion(question, index) {
  const suffix = []
  if (question.options.length > 0) suffix.push(`选项：${question.options.join(' / ')}`)
  if (question.multiSelect) suffix.push('可多选')
  return `${index + 1}. ${question.text}${suffix.length > 0 ? `（${suffix.join('；')}）` : ''}`
}

function renderBank(bank) {
  return bank.dimensions
    .filter((dimension) => dimension.questions.length > 0)
    .map((dimension) => {
      const lines = [`### ${dimension.title}`]
      dimension.questions.forEach((question, index) => lines.push(renderQuestion(question, index)))
      return lines.join('\n')
    })
    .join('\n\n')
}

export function skillMeta(config) {
  if (config.language === 'en') {
    return {
      description:
        'Inquiry clarification: ask 20-30 concrete questions in rounds, recap after each round, then turn the answers into a requirement brief before building.',
      whenToUse:
        'The user gives a vague seed (one sentence, a screenshot, casual speech, "I want to build something") and the goal is to create, design, change, or explore; or key requirements must be pulled out before work starts.',
    }
  }
  return {
    description:
      '问答式澄清：用 20~30 个具体问题分 3-5 轮把模糊想法问成可执行方向，每轮复述理解，最后收口成《需求简报》。',
    whenToUse:
      '用户只给了一个说不清的种子（一句话、截图、口语、一个"我想要个东西"）却要创造、设计、改造、探索时；或动手前需要补齐关键信息、防止口语化把需求遮蔽时。',
  }
}

export function buildSkillContent({ config, bank, source = 'builtin', path = '', warnings = [] }) {
  const isEn = config.language === 'en'
  const total = totalQuestions(config)
  const bankLabel = source === 'custom' ? `custom: ${path}` : isEn ? 'built-in (en)' : '内置（zh）'
  const configLines = isEn
    ? [
        `- rounds: ${config.rounds}`,
        `- questions per round: ${config.questionsPerRound} (about ${total} total)`,
        `- language: English`,
        `- question bank: ${bankLabel}`,
        `- brief directory: ${config.briefDir}`,
      ]
    : [
        `- 轮数：${config.rounds}`,
        `- 每轮题数：${config.questionsPerRound}（总计约 ${total} 题）`,
        `- 语言：中文`,
        `- 题库：${bankLabel}`,
        `- 简报目录：${config.briefDir}`,
      ]

  const warningBlock =
    warnings.length > 0
      ? isEn
        ? `> ⚠️ ${warnings.join(' / ')}\n\n`
        : `> ⚠️ ${warnings.join('；')}\n\n`
      : ''

  if (isEn) {
    return `# Inquiry Mode: requirement clarification

> Generated by dsh-inquiry-mode from the current config. It rebuilds when the config changes.

${warningBlock}## Current config
${configLines.join('\n')}

## Goal
Do not wait for a complete description. Most users can only recall 3%-40% of what they want up front, so use hypotheses and concrete options to pull out the rest, and let them answer "yes / no" to something specific.

## Round structure
0. Open with a direction: say what you think they want in one sentence, then offer 3 possible directions.
1. State your hypothesis first, so they can correct it.
2. Ask ${config.questionsPerRound} concrete questions in ONE ask_user_question call (one question per page, skippable, free text allowed). Put the recommended option first and append \`(Recommended)\` to its label.
3. After the answers, recap in 3 blocks: [Confirmed] [My inference] [Still missing], then ask "did anything else come back to you? add it in any order".
4. Only ask what the next round still lacks; stop as soon as you can build.

## Question formula
- One topic per question. Do not put the answer in the question stem; put the recommendation in the options.
- Make options concrete enough to pick: names, numbers, behaviors. Never use vague adjectives.
- If the user says "whatever / you decide / no idea", offer 2-3 concrete examples or decide and mark "I chose X, changeable".
- Do not ask what you can look up or infer; write it as [My inference].

## Question bank (pick by seed type; not all are needed)
${renderBank(bank)}

${bank.notes ? `${bank.notes}\n\n` : ''}## Round recap template
\`\`\`
[Understanding snapshot · round N]
[Confirmed] ... (what the user explicitly said)
[My inference] ... (what you guessed; ask them to confirm)
[Still missing] ... (2-3 gaps for the next round)
\`\`\`
End with: "Did anything else come back to you? Add it in any order."

## Requirement brief template
\`\`\`markdown
# Requirement brief: <topic>
- Goal (one sentence):
- Users and scenarios:
- Deliverable form:
- Must have (P0):
- Later (P1):
- Explicitly out of scope:
- Acceptance criteria (checkable):
- Constraints and dependencies:
- Assumptions and risks:
\`\`\`

## Closing
When coverage is enough (or the user says stop), output the brief, save it under \`${config.briefDir}\`, and use ask_user_question with: "Build it as described (Recommended) / I need a few changes / Not yet". Start building only after confirmation.

## Anti-patterns
- Do not dump 20 questions at once; users answer carelessly and you cannot adapt.
- Do not ask what you can inspect yourself.
- Do not mix [My inference] into [Confirmed].
- Do not start building without a summary.
- Do not keep asking after the user says "enough".
- Do not use open-ended "what else do you want" instead of concrete options.
`
  }

  return `# 刨根问底：问答式需求澄清

> 由 dsh-inquiry-mode 按当前配置生成；改配置后自动重建。

${warningBlock}## 当前配置
${configLines.join('\n')}

## 目标
不要等用户把需求说全。用户通常只能复述 3%-40%，用假设和具体选项去逼出剩下的部分，让他对"具体的东西"说对/不对。

## 每轮的结构
0. 开场先给方向：一句话说出你猜他要做什么，再给 3 个可能方向。
1. 先给假设，让他先纠偏。
2. 一次问 ${config.questionsPerRound} 个具体问题，放在同一次 ask_user_question 调用里（一题一页，可跳过、可自填）。推荐项放第一，标签末尾加 \`(Recommended)\`。
3. 收到答案后复述三栏：**【已确认】【我的推断】【还差的】**，再问"刚才有没有又想起什么？直接补充，不用按顺序"。
4. 只问下一轮真正缺的；够开工就收口。

## 提问公式
- 一题一件事；题干里不带答案倾向，推荐放在选项里。
- 选项要具体到能直接选：名词、数字、行为，不用"高级/简洁/流畅"这类词。
- 用户答"随便 / 你定 / 不知道"→ 给 2-3 个具体例子让他挑，或替他做决定并标注"我按 X 定了，随时可改"。
- 能从上下文推断或自己查到的，不问；写成【我的推断】让他点头。

## 问题库（按种子类型取舍，不必全问）
${renderBank(bank)}

${bank.notes ? `${bank.notes}\n\n` : ''}## 每轮复述模板
\`\`\`
【理解快照 · 第 N 轮】
【已确认】…（用户明确说过的，3-5 条）
【我的推断】…（没问但猜的，标注"推断"，请点头或纠正）
【还差的】…（2-3 个关键缺口，下一轮问）
\`\`\`
末尾加一句："刚才有没有又想起什么？直接补充，不用按顺序。"

## 需求简报模板
\`\`\`markdown
# 需求简报：<主题>
- 目标（一句话）：
- 使用者与场景：
- 交付物形态：
- 必须做到（P0）：
- 可以以后做（P1）：
- 明确不做：
- 验收标准（可检查）：
- 约束与依赖：
- 假设与风险：
\`\`\`

## 收口
覆盖足够（或用户喊停）后，输出《需求简报》，保存到 \`${config.briefDir}\`，然后用 ask_user_question 给三选一：「就按这个做（Recommended）/ 我要改几处 / 先别做」。用户确认后才动手。

## 反模式
- 一口气弹 20 题：用户会乱答，且你无法根据答案调整。
- 问能自己查到的事。
- 把"我的推断"混进"已确认"。
- 问完不总结，直接开工。
- 用户说"够了"还继续问。
- 用"你还想要什么"这种开放式空题代替具体选项。
`
}

export function buildCommandPrompt({ config, rawInput = '' }) {
  const seed = String(rawInput ?? '').trim()
  const total = totalQuestions(config)
  if (config.language === 'en') {
    const lines = [
      '【Inquiry mode · triggered by command】',
      'Enter requirement-clarification mode now. Combine ALL information already in this conversation (what I said, screenshots, files, corrections) and do not repeat questions I already answered.',
      config.autoLoadSkill
        ? 'Load the `inquiry-mode` skill first and follow its config.'
        : 'Follow the protocol in this message (the skill is optional).',
      `1. Recap in 3-6 lines: [Confirmed] [My inference] [Still missing].`,
      `2. Use ask_user_question to offer 3 possible directions (recommended option first, label ending with (Recommended)).`,
      `3. Then ${config.questionsPerRound} questions per round, ${config.rounds} rounds (about ${total} total). After each round, recap the 3 blocks and ask "did anything else come back to you?".`,
      `4. When coverage is enough, output the requirement brief, save it under ${config.briefDir}, and use ask_user_question with: "Build it as described (Recommended) / I need a few changes / Not yet". Do not build before my confirmation.`,
      `5. If I say "enough / just build it", close the interview immediately.`,
    ]
    if (seed) lines.push('', 'My addition (part of the seed):', seed)
    return lines.join('\n')
  }

  const lines = [
    '【刨根问底 · 由命令触发】',
    '现在进入问答澄清模式，并综合本会话此前的全部信息（我说过的话、截图、文件、我纠正过的地方），不要重复问已经答过的。',
    config.autoLoadSkill
      ? '先加载 `inquiry-mode` 技能，按它的配置执行。'
      : '按本消息的协议执行（技能可选）。',
    '1. 先用 3-6 行复述你目前的理解：【已确认】【我的推断】【还差的】。',
    '2. 用 ask_user_question 给我 3 个可能方向（推荐项放第一，标签末尾加 (Recommended)）。',
    `3. 之后每轮 ${config.questionsPerRound} 题（一题一页）、共 ${config.rounds} 轮（约 ${total} 题）；每轮结束复述三栏，并问 "刚才有没有又想起什么"。`,
    `4. 覆盖够了给《需求简报》，保存到 ${config.briefDir}，用 ask_user_question 让我选「就按这个做（Recommended）/ 我要改几处 / 先别做」；我确认前不要动手。`,
    '5. 我说「够了 / 直接做」就立即收口。',
  ]
  if (seed) lines.push('', '我的补充（算作种子的一部分）：', seed)
  return lines.join('\n')
}
